// Use the real research hub, new-study action and follow-up drafting functions.
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const nodes=new Map(),storage=new Map(),calls=[],handlers={};
const node=selector=>{if(!nodes.has(selector))nodes.set(selector,{value:"",checked:false,hidden:false,innerHTML:"",dataset:{},classList:{add(){},remove(){}},focus(){},scrollIntoView(){},querySelector:node,querySelectorAll:()=>[],addEventListener(){}});return nodes.get(selector);};
const context={document:{querySelector:node,querySelectorAll:()=>[],addEventListener(name,fn){(handlers[name]||=[]).push(fn);}},window:{addEventListener(){}},location:{hash:"#research/a"},sessionStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)},URL,URLSearchParams,console,setTimeout,clearTimeout,Intl};
vm.createContext(context);vm.runInContext(fs.readFileSync(process.argv[2],"utf8"),context);
context.items=[{id:"a",title:"<script>接口研究</script>",goal:"任务与责任",state:"active",step_count:1,job_count:2,document_count:1,last_question:"谁负责验收？"},{id:"b",title:"RAG 项目",goal:"能力迁移",state:"active",step_count:2,job_count:1,document_count:0},{id:"forgotten",title:"已忘记的研究内容",state:"invalidated"}];
context.calls=calls;context.project={id:"a",title:"接口研究",goal:"任务与责任",state:"active",worker_running:false,steps:[{id:"step-a",run_id:"run-a",question:"谁负责验收？",state:"waiting_material",result:{status:"evidence_only"}}],budget:{max_calls:24,max_seconds:720,max_rounds:6,max_public:0},usage:{reserved_calls:0,reserved_seconds:0,public:0}};
vm.runInContext('api=async path=>{calls.push(path);return items};notify=()=>{};',context);
(async()=>{
 await vm.runInContext('loadResearchProjects()',context);
 let html=node("#research-project-list").innerHTML;
 assert.ok(html.includes("&lt;script&gt;接口研究&lt;/script&gt;")&&!html.includes("<script>"));
 assert.ok(html.includes("RAG 项目")&&!html.includes("已忘记的研究内容"));
 node("#research-project-query").value="验收";vm.runInContext('renderResearchProjects()',context);
 html=node("#research-project-list").innerHTML;assert.ok(html.includes('data-open-conversation="a"')&&!html.includes('data-open-conversation="b"'));
 node("#conversation-question").value="还没发出的追问";
 vm.runInContext('conversation.id="a";conversation.renderedId="a";conversation.project=project;prepareNewResearch()',context);
 assert.equal(node("#research-form").hidden,false);assert.equal(node("#research-output").innerHTML,"");
 assert.equal(vm.runInContext('conversation.drafts.get("a").question',context),"还没发出的追问");
 assert.equal(calls.length,1); // Preparing another study does not execute anything.
 const actions=vm.runInContext('renderResearchNextActions(project)',context);
 assert.ok(actions.includes("找反例与边界")&&actions.includes("整理阶段成果")&&actions.includes("用 AI 分析这些原文"));
 vm.runInContext('conversation.id="a";conversation.project=project;prefillConversationFollowup({dataset:{conversationFollowup:"整理已有认识",followupKind:"synthesis",replyStep:"step-a"}})',context);
 assert.equal(node("#conversation-kind").value,"synthesis");
 assert.ok(node("#conversation-question").value.includes("整理已有认识"));
 node("#conversation-question").value="保留我的具体问题";
 node("#conversation-offline").checked=true;
 vm.runInContext('prepareEvidenceAnalysis()',context);
 assert.equal(node("#conversation-offline").checked,false);
 assert.equal(node("#conversation-question").value,"保留我的具体问题");assert.equal(calls.length,1);
 context.jobs=[{id:"job-one",title:"<b>接口岗位</b>",company:"合成公司",city:"上海",has_detail:true}];
 vm.runInContext('api=async()=>({jobs});',context);
 await vm.runInContext('loadResearchJobChoices()',context);
 assert.ok(node("#research-job-list").innerHTML.includes("&lt;b&gt;接口岗位&lt;/b&gt;"));
 const check={id:"job-check",checked:true,dataset:{researchJob:"job-one"},closest(selector){return selector==="[data-research-job]"?this:null;},matches(){return false;}};
 for(const handler of handlers.change)await handler({target:check});
 assert.deepEqual(Array.from(vm.runInContext('state.researchIds',context)),["job-one"]);
 assert.equal(node("#research-source-mode").value,"jobs");
 assert.ok(node("#research-scope").innerHTML.includes("接口岗位"));
 context.bookmarkCalls=[];
 vm.runInContext('conversation.id=null;api=async(path,options)=>{bookmarkCalls.push({path,options});return {id:"saved-claim"};};',context);
 context.bookmark={dataset:{knowledgeRun:"run-a",claimIndex:"0",knowledgeProject:"a"},disabled:false,textContent:""};
 await vm.runInContext('collectResearchClaim(bookmark)',context);
 assert.equal(context.bookmarkCalls.length,2);
 const saved=JSON.parse(context.bookmarkCalls[0].options.body);
 assert.equal(saved.scope,"project");assert.equal(saved.project_id,"a");assert.equal(saved.claim_index,0);
 assert.equal(context.bookmarkCalls[1].path,"memories/saved-claim/activate");
 assert.equal(context.bookmark.textContent,"已收藏 ✓");
 console.log("Research hub: find studies, keep drafts, start fresh and prepare deeper questions passed.");
})().catch(error=>{console.error(error);process.exitCode=1;});
