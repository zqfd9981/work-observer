// The common cohort uses full frozen counts, links both sources, and scopes a saved new study.
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict"),path=require("node:path");
const listeners=[],calls=[],notices=[];
const node=()=>({querySelector:node,querySelectorAll:()=>[],addEventListener(){}});
const ctx={document:{querySelector:node,querySelectorAll:()=>[],addEventListener(type,fn){listeners.push({type,fn});}},window:{addEventListener(){}},location:{hash:""},URL,console,setTimeout,clearTimeout,Intl};
vm.createContext(ctx);vm.runInContext(fs.readFileSync(process.argv[2],"utf8"),ctx);
listeners.length=0;
vm.runInContext(fs.readFileSync(path.join(path.dirname(process.argv[2]),"updates.js"),"utf8"),ctx);
const source={document_id:"old-doc",observed_at:"2026-11-01T00:00:00+00:00"};
ctx.report={id:"report",job_ids:["common","added"],common_cohort:{comparable:true,shared_jobs:2,denominator:1,job_ids:["common"],notice:"仅是字面对照，不是需求趋势",excluded:[{job_id:"incomplete",reasons:["before_not_eligible"]}],statistics:[{term:"<img>Python",before:1,after:0,denominator:1,newly_mentioned_job_ids:[],no_longer_mentioned_job_ids:["common"]}],uncompared_terms:{before:["Go"],after:[]},jobs:[{job_id:"common",title:"<script>合成任务",before:{source,literal_hits:["Python"]},after:{source:{...source,document_id:"new-doc"},literal_hits:[]}}]}};
let html=vm.runInContext("renderCommonCohort(report)",ctx);
assert.ok(html.includes("1/1")&&html.includes("0/1")&&html.includes("较早侧缺少明确范围"));
assert.ok(html.includes('data-source="old-doc"')&&html.includes('data-source="new-doc"'));
assert.ok(html.includes("不能当成零命中")&&html.includes("&lt;img&gt;")&&html.includes("&lt;script&gt;"));
assert.ok(!html.includes("<img>")&&!html.includes("<script>"));
assert.ok(vm.runInContext("renderCohortScope(report)",ctx).includes('name="common_cohort"'));
assert.ok(vm.runInContext("renderCommonCohort({})",ctx).includes("不能用现在的正文补算过去"));
ctx.unavailable={common_cohort:{...ctx.report.common_cohort,comparable:false,reasons:["matching_changed_or_unrecorded"],statistics:[]}};
html=vm.runInContext("renderCommonCohort(unavailable)",ctx);
assert.ok(html.includes("缺记录保持未知，不补成零")&&!html.includes("1/1"));
ctx.calls=calls;ctx.notices=notices;
vm.runInContext('currentUpdateReport=report;notify=(text,error)=>notices.push({text,error});api=async(route,options)=>{calls.push({route,body:JSON.parse(options.body)});if(route.endsWith("/followup"))return {question:"报告中的两个截止",job_ids:report.job_ids};if(route==="projects")return {id:"new-project",revision:1};return {};};',ctx);
const button={value:"project",disabled:false};
const form={id:"update-followup",matches(){return false;},elements:{note:{value:"核对两次接口工作"},common_cohort:{checked:true}},querySelectorAll(){return [];}};
const event={target:form,submitter:button,preventDefault(){}};
(async()=>{
  for(const item of listeners.filter(row=>row.type==="submit"))await item.fn(event);
  assert.equal(calls.length,3);assert.ok(!notices.some(row=>row.error));
  assert.deepEqual(Array.from(calls[1].body.job_ids),["common"]);
  assert.equal(calls[1].body.source_key,"domain-update:report:common-cohort");
  assert.ok(calls[1].body.goal.includes("仅限报告的共同正文样本"));
  assert.ok(calls[2].body.completion.includes("两个来源截止"));
  assert.ok(calls.every(row=>!row.route.includes("/run")&&!row.route.includes("/continue")));
  assert.equal(button.disabled,false);assert.equal(ctx.location.hash,"#projects");
  calls.length=0;form.elements.common_cohort.checked=false;
  for(const item of listeners.filter(row=>row.type==="submit"))await item.fn(event);
  assert.deepEqual(Array.from(calls[1].body.job_ids),["common","added"]);
  assert.equal(calls[1].body.source_key,"domain-update:report");
  console.log("Common cohort: frozen counts, missing history, source links, escaping and scoped project save passed.");
})().catch(error=>{console.error(error);process.exitCode=1;});
